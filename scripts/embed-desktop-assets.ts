import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, extname, join } from "node:path";

const [output, ...options] = process.argv.slice(2);
if (!output)
  throw new Error("Expected <output-module> [--directory <path>] [--file <url> <path>]...");
const directories: string[] = [];
const files: [string, string][] = [];
for (let index = 0; index < options.length; ) {
  const option = options[index++];
  switch (option) {
    case "--directory": {
      const path = options[index++];
      if (!path) throw new Error("Missing --directory path");
      directories.push(path);
      break;
    }
    case "--file": {
      const url = options[index++];
      const path = options[index++];
      if (!url?.startsWith("/") || !path)
        throw new Error("Expected --file <absolute-url-path> <file-path>");
      files.push([url, path]);
      break;
    }
    default:
      throw new Error(`Unknown asset option ${option}`);
  }
}
const contentTypes: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".woff": "font/woff",
  ".woff2": "font/woff2",
  ".wasm": "application/wasm",
};
const entries = new Map<string, string>();
async function add(path: string, key: string) {
  if (entries.has(key)) throw new Error(`Duplicate asset URL ${key}`);
  const body = (await readFile(path)).toString("base64");
  const contentType = contentTypes[extname(path)] ?? "application/octet-stream";
  entries.set(
    key,
    `[${JSON.stringify(key)}, { contentType: ${JSON.stringify(contentType)}, body: Uint8Array.from(atob(${JSON.stringify(body)}), (value) => value.charCodeAt(0)) }]`,
  );
}
async function walk(path: string, prefix: string) {
  const items = await readdir(path, { withFileTypes: true });
  items.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0));
  for (const item of items) {
    const file = join(path, item.name);
    const key = `${prefix}/${encodeURIComponent(item.name)}`;
    if (item.isDirectory()) await walk(file, key);
    else if (item.isFile()) await add(file, key);
    else throw new Error(`Unsupported asset entry ${file}`);
  }
}
for (const directory of directories) await walk(directory, "");
for (const [url, path] of files) await add(path, url);
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/embed-desktop-assets.ts; do not edit.\nexport const assets = new Map<string, { readonly body: Uint8Array; readonly contentType: string }>([\n${[...entries.values()].join(",\n")}\n]);\n`,
);
