import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import * as NM from "@nomake/core";

const [crate, output, ...extra] = process.argv.slice(2);
if (!crate || !output || extra.length > 0) {
  throw new Error("Usage: node scripts/build-rust-wasm.ts <crate> <output>");
}

await NM.Shell.runChecked(
  [
    "cargo",
    "rustc",
    "--locked",
    "-p",
    crate,
    "--lib",
    "--release",
    "--target",
    "wasm32-unknown-unknown",
    "--crate-type",
    "cdylib",
  ],
  { cwd: "rust-workspace" },
);

const wasm = `rust-workspace/target/wasm32-unknown-unknown/release/${crate.replaceAll("-", "_")}.wasm`;
const bytes = await readFile(wasm);
await mkdir(dirname(output), { recursive: true });
await writeFile(
  output,
  `// Generated by scripts/build-rust-wasm.ts; do not edit.\nexport const WASM_BASE64 = ${JSON.stringify(bytes.toString("base64"))};\n`,
);
