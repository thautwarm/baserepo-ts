import { readFile, writeFile } from "node:fs/promises";
import { dirname, relative, sep } from "node:path";
import { generate } from "ts-to-zod";
import { publicModelNames } from "./schema-models.ts";

const [source, target, ...extra] = process.argv.slice(2);
if (!source || !target || extra.length > 0) {
  throw new Error("Usage: node scripts/schemas.ts <input> <output>");
}

const sourceText = await readFile(source, "utf8");
const models = publicModelNames(sourceText);
const hasPublicModels = models.has("PublicModels");
const result = generate({
  sourceText,
  nameFilter: (name) => models.has(name),
});
if (result.errors.length > 0) throw new Error(result.errors.join("\n"));

const sourceImport = relative(dirname(target), source).split(sep).join("/");
const output = result.getZodSchemasFile(
  sourceImport.startsWith("../") ? sourceImport : `./${sourceImport}`,
);
if (hasPublicModels && !output.includes("export const publicModelsSchema =")) {
  throw new Error(`${source}: PublicModels must be exported`);
}
await writeFile(
  target,
  hasPublicModels ? output : "// Generated by scripts/schemas.ts\nexport {};\n",
);
